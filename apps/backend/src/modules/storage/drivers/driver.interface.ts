import type {
  InstallPlan,
  SharedStorageConfig,
  StorageBackend,
} from '@swarmui-master/storage-plan';

// Strategy interface for a storage backend driver.
// A driver is responsible for turning a user config into a deterministic
// install plan (steps are node-exec calls) and for the inverse teardown plan.
// storage-core owns the state machine, audit, HMAC, SSE streaming; drivers own
// only the "what to run on which node" decision.
export interface IStorageDriver {
  // Which backend this driver handles. Used by the registry to route by
  // SharedStorageConfig.backend.
  readonly backend: StorageBackend;

  // Build an install plan. Pure function of config + swarm topology; must not
  // read the DB or hit the network. The sessionId is generated by storage-core
  // and threaded into every step so HMAC signing is unambiguous.
  plan(
    config: SharedStorageConfig,
    sessionId: string,
  ): InstallPlan | Promise<InstallPlan>;

  // Build an uninstall plan. Must be idempotent per step so the state machine
  // can retry individual steps after transient failures without side-effecting
  // the earlier ones.
  uninstallPlan(
    config: SharedStorageConfig,
    sessionId: string,
  ): InstallPlan | Promise<InstallPlan>;

  // Enumerate stacks / services that currently bind-mount the shared
  // mountPoint. Called before uninstall to refuse a destructive teardown while
  // consumers remain. Returns a list of human-readable identifiers.
  enumerateConsumers(mountPoint: string): Promise<string[]>;
}
